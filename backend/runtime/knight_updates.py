"""Owner-configured, unprivileged systemd source updates with rollback.

No profile is created automatically. Pairing alone grants no update authority.
This module does not install dependencies, run package scripts, or touch OS disks.
"""
import base64
import hashlib
import io
import json
import os
from pathlib import Path, PurePosixPath
import re
import sqlite3
import subprocess
import sys
import tarfile
import time
import urllib.request

MAX_ARCHIVE = 32 * 1024 * 1024
MAX_CONTENT = 64 * 1024 * 1024


def record_receipt(state_root, receipt):
    """Durable state in the normal database; JSON remains a portable evidence copy."""
    data = Path(state_root) / 'data'
    data.mkdir(parents=True, exist_ok=True)
    with sqlite3.connect(data / 'kingdom.db') as connection:
        connection.execute('CREATE TABLE IF NOT EXISTS knight_update_receipts(release TEXT PRIMARY KEY, receipt_json TEXT NOT NULL)')
        connection.execute('INSERT INTO knight_update_receipts VALUES(?,?) ON CONFLICT(release) DO UPDATE SET receipt_json=excluded.receipt_json',
                           (receipt['release'], json.dumps(receipt)))
    (data / ('update-' + receipt['release'] + '.json')).write_text(json.dumps(receipt))


def read_receipt(state_root, release):
    path = Path(state_root) / 'data/kingdom.db'
    if not path.is_file():
        return {'status': 'no_receipt', 'verified': False}
    with sqlite3.connect(path) as connection:
        if not connection.execute("SELECT 1 FROM sqlite_master WHERE name='knight_update_receipts'").fetchone():
            return {'status': 'no_receipt', 'verified': False}
        row = connection.execute('SELECT receipt_json FROM knight_update_receipts WHERE release=?', (release,)).fetchone()
    return json.loads(row[0]) if row else {'status': 'no_receipt', 'verified': False}


def digest(value):
    return hashlib.sha256(value).hexdigest()


def stage(root, archive_b64, expected_sha):
    """Expand regular files only; immutable hash identity binds staged bytes."""
    if not isinstance(expected_sha, str) or not re.fullmatch(r'[0-9a-f]{64}', expected_sha):
        raise ValueError('Expected an exact SHA256 archive digest')
    if not isinstance(archive_b64, str) or len(archive_b64) > MAX_ARCHIVE * 4 // 3 + 4:
        raise ValueError('Update archive exceeds transfer budget')
    try:
        raw = base64.b64decode(archive_b64, validate=True)
    except (ValueError, TypeError) as error:
        raise ValueError('Invalid base64 archive') from error
    if len(raw) > MAX_ARCHIVE or digest(raw) != expected_sha:
        raise ValueError('Update archive hash mismatch or size exceeded')
    root = Path(root).resolve()
    root.mkdir(parents=True, exist_ok=True)
    target = root / expected_sha
    if target.exists():
        raise ValueError('Release already exists; verify or use the existing receipt')
    files = {}
    with tarfile.open(fileobj=io.BytesIO(raw), mode='r:*') as archive:
        total = 0
        for index, member in enumerate(archive):
            if index >= 10000 or len(member.name) > 500:
                raise ValueError('Update file count or name budget exceeded')
            name = PurePosixPath(member.name)
            if (not member.isfile() and not member.isdir()) or name.is_absolute() or '..' in name.parts or '\\' in member.name or ':' in member.name:
                raise ValueError('Only relative regular files and directories are accepted')
            if str(name) == 'update-manifest.json' or any(part in {'data', '.git', '.env', '__pycache__'} for part in name.parts):
                raise ValueError('Update must exclude private state and generated bytecode')
            if member.isdir():
                continue
            total += member.size
            if member.size > MAX_CONTENT or total > MAX_CONTENT or str(name) in files:
                raise ValueError('Update content budget exceeded or duplicate path')
            content = archive.extractfile(member).read()
            if str(name).startswith('backend/') and str(name).endswith('.py'):
                compile(content, str(name), 'exec')
            files[str(name)] = content
    if 'backend/main.py' not in files:
        raise ValueError('Expected a Kingdom source release')
    temporary = root / ('.incoming-' + expected_sha)
    temporary.mkdir(exist_ok=False)
    try:
        manifest = {}
        for name, content in files.items():
            path = temporary / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
            manifest[name] = digest(content)
        (temporary / 'update-manifest.json').write_text(json.dumps(manifest, sort_keys=True))
        temporary.rename(target)
    except BaseException:
        import shutil
        shutil.rmtree(temporary)
        raise
    return {'status': 'staged', 'release': expected_sha, 'files': len(files), 'bytes': total,
            'deployed': False}


def verify(source):
    source = Path(source).resolve()
    manifest = json.loads((source / 'update-manifest.json').read_text())
    actual = {str(p.relative_to(source).as_posix()) for p in source.rglob('*') if p.is_file()}
    if actual != set(manifest) | {'update-manifest.json'}:
        raise ValueError('Staged file set changed')
    for name, checksum in manifest.items():
        path = source / name
        if any(p.is_symlink() for p in (path, *path.parents)) or digest(path.read_bytes()) != checksum:
            raise ValueError('Staged content changed')
    return manifest


def load_profile(path):
    profile = json.loads(Path(path).read_text())
    home = Path.home().resolve()
    unit = Path(profile['unit_file']).resolve()
    if unit.parent != home / '.config/systemd/user' or not re.fullmatch(r'[a-zA-Z0-9_.@-]+\.service', unit.name):
        raise ValueError('Updater only manages an explicitly configured user service')
    for key in ('releases_root', 'state_root', 'python'):
        value = Path(profile[key])
        if not value.is_absolute() or any(c.isspace() or c in '\"%' for c in str(value)):
            raise ValueError('Use absolute local paths without systemd expansion syntax')
    if not re.fullmatch(r'http://127\.0\.0\.1:[0-9]{1,5}', profile['base_url']):
        raise ValueError('Health verification must use local loopback HTTP')
    return profile


def activate(profile_path, release):
    profile = load_profile(profile_path)
    lock = Path(profile['state_root']) / 'data/knight-update.lock'
    lock.mkdir(exist_ok=False)
    try:
        return _activate(profile_path, release)
    except BaseException as error:
        receipt = read_receipt(profile['state_root'], release)
        if receipt.get('status') not in {'rolled_back', 'rollback_failed'}:
            record_receipt(profile['state_root'], {'release': release, 'status': 'blocked',
                           'failure_class': type(error).__name__, 'completed_at': time.time(), 'verified': False})
        raise
    finally:
        lock.rmdir()


def _activate(profile_path, release):
    """Called from a separate user service so restarting Kingdom cannot kill it."""
    if not re.fullmatch(r'[0-9a-f]{64}', release):
        raise ValueError('Invalid release digest')
    profile = load_profile(profile_path)
    source = Path(profile['releases_root']) / release
    manifest = verify(source)
    unit = Path(profile['unit_file'])
    old = unit.read_text()
    entries = [line for line in old.splitlines() if line.startswith('Environment=PYTHONPATH=')]
    if len(entries) != 1:
        raise ValueError('Configured service must have exactly one explicit PYTHONPATH')
    token = (Path(profile['state_root']) / 'data/owner-token').read_text().strip()

    def api(path):
        req = urllib.request.Request(profile['base_url'] + path, headers={'Authorization': 'Bearer ' + token})
        with urllib.request.urlopen(req, timeout=5) as response:
            return json.load(response)

    before = api('/nodes/identity')
    # The scheduling task itself may still be settling when this transient
    # service starts. Wait briefly; never exclude tasks by caller metadata.
    for attempt in range(20):
        busy = any(t['status'].lower() in {'running', 'leased', 'queued', 'waiting_approval'} for t in api('/tasks'))
        if not busy:
            break
        if attempt == 19:
            raise ValueError('Drain outstanding tasks before updating this Knight')
        time.sleep(0.25)
    with sqlite3.connect(Path(profile['state_root']) / 'data/kingdom.db') as connection:
        for table in ('agent_sessions', 'conversation_requests'):
            if connection.execute('SELECT 1 FROM sqlite_master WHERE type="table" AND name=?', (table,)).fetchone():
                # State documents are intentionally checked before changing the unit.
                columns = [row[1] for row in connection.execute('PRAGMA table_info(' + table + ')')]
                column = 'state_json' if 'state_json' in columns else None
                if column:
                    for row in connection.execute('SELECT ' + column + ' FROM ' + table):
                        state = json.loads(row[0])
                        if state.get('status', state.get('state')) not in {'completed', 'failed', 'cancelled', 'blocked', 'exhausted'}:
                            raise ValueError('Pause or complete agent sessions before updating')
    receipt = {'release': release, 'status': 'activating', 'started_at': time.time()}
    record_receipt(profile['state_root'], receipt)

    def restart():
        subprocess.run(['systemctl', '--user', 'daemon-reload'], check=True, timeout=30)
        subprocess.run(['systemctl', '--user', 'restart', unit.name], check=True, timeout=60)

    backup = unit.with_suffix('.before-' + release)
    backup.write_text(old)
    try:
        replacement = 'Environment=PYTHONPATH=' + str(source)
        if 'Environment=PYTHONDONTWRITEBYTECODE=1' not in old:
            replacement += '\nEnvironment=PYTHONDONTWRITEBYTECODE=1'
        updated = '\n'.join(replacement if line.startswith('Environment=PYTHONPATH=') else line for line in old.splitlines()) + '\n'
        unit.write_text(updated)
        restart()
        last_error = None
        for _ in range(40):
            try:
                if api('/nodes/identity') != before:
                    raise ValueError('Identity changed during update')
                if api('/health/ready').get('status') != 'ready':
                    raise ValueError('Updated service is not ready')
                observed = api('/knight-management/local-source')
                if (observed.get('root') != str(source.resolve())
                        or observed.get('main_sha256') != manifest['backend/main.py']):
                    raise ValueError('Running backend does not match the staged source')
                last_error = None
                break
            except Exception as error:
                last_error = error
                time.sleep(1)
        if last_error:
            raise ValueError('Updated service failed independent identity/readiness checks') from last_error
        receipt.update(status='verified', identity_preserved=True, runtime_source_verified=True)
    except BaseException:
        unit.write_text(old)
        try:
            restart()
            receipt.update(status='rolled_back', rollback_ready=api('/health/ready').get('status') == 'ready',
                           identity_preserved=api('/nodes/identity') == before)
        except Exception:
            receipt.update(status='rollback_failed')
        raise
    finally:
        receipt['completed_at'] = time.time()
        record_receipt(profile['state_root'], receipt)
    return receipt


def schedule_command(profile_path, release):
    if not re.fullmatch(r'[0-9a-f]{64}', release):
        raise ValueError('Invalid release digest')
    profile = load_profile(profile_path)
    verify(Path(profile['releases_root']) / release)
    # No shell. Profile is local operator configuration, never supplied by a peer.
    if os.name != 'posix' or not hasattr(os, 'getuid'):
        raise ValueError('This optional update adapter requires a systemd Linux user service')
    runtime = '/run/user/' + str(os.getuid())
    argv = ['/usr/bin/env', 'XDG_RUNTIME_DIR=' + runtime,
            'DBUS_SESSION_BUS_ADDRESS=unix:path=' + runtime + '/bus',
            '/usr/bin/systemd-run', '--user', '--collect', '--unit=kingdom-update-' + release[:20],
            profile['python'], str(Path(__file__).resolve()), '--activate', str(Path(profile_path).resolve()), release]
    return argv


if __name__ == '__main__':
    if len(sys.argv) != 4 or sys.argv[1] != '--activate':
        raise SystemExit('Use the installed owner-configured updater')
    print(json.dumps(activate(sys.argv[2], sys.argv[3])))
